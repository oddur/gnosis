import { loadWorkbenchPage, waitForWorkbenchQueue } from './workbench-ready';
import assert from 'node:assert/strict';
import { app, BrowserWindow } from 'electron';
import fs from 'node:fs';
import path from 'node:path';
void app.whenReady().then(async () => {
  const win = new BrowserWindow({ width: 1280, height: 850, show: true, webPreferences: { backgroundThrottling: false } });
  win.webContents.on('console-message', ({ level, message }) => { if (level === 'error') console.error(message); });
  const js = <T = unknown>(code: string) => win.webContents.executeJavaScript(code) as Promise<T>;
  const wait = async (code: string, attempts = 160) => { for (let i = 0; i < attempts; i++) { if (await js(code)) return; await new Promise(r => setTimeout(r, 30)); } throw Error('Timed out: ' + code); };
  const click = async (selector: string) => { await js(`(()=>{const b=document.querySelector(${JSON.stringify(selector)});b.dispatchEvent(new MouseEvent('mousedown',{bubbles:true,button:0}));b.click()})()`); await new Promise(r => setTimeout(r, 50)); };
  const button = (text: string) => js(`[...document.querySelectorAll('.repository-editor button')].find(b=>b.textContent.trim()===${JSON.stringify(text)}).click()`);
  const fill = (selector: string, value: string) => js(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(e,${JSON.stringify(value)});e.dispatchEvent(new Event('input',{bubbles:true}));})()`);
  const capture = async (name: string) => { await js('document.fonts.ready'); await new Promise(r => setTimeout(r, 200)); const dir=path.resolve('.impeccable/review/repository-settings');fs.mkdirSync(dir,{recursive:true});fs.writeFileSync(path.join(dir,name+'.png'),(await win.webContents.capturePage()).toPNG()); };
  try {
    const fixtureUrl = process.env.GNOSIS_WORKBENCH_URL;
    assert.ok(fixtureUrl);
    await loadWorkbenchPage(win, fixtureUrl + '?filters');
    win.webContents.debugger.attach('1.3');
    await win.webContents.debugger.sendCommand('Emulation.setFocusEmulationEnabled', { enabled: true });
    await waitForWorkbenchQueue(win.webContents);
    await js("(()=>{const snapshot=window.electronAPI.workbenchSnapshot;window.electronAPI.workbenchSnapshot=async()=>({...await snapshot(),briefingBudget:{limit:10,used:3,remaining:7,resetsAt:new Date().toISOString(),repositories:{'klang/engine':{limit:10,used:2,remaining:8,automatic:true}}}})})()");
    await js("document.body.dispatchEvent(new KeyboardEvent('keydown',{key:',',metaKey:true,bubbles:true,cancelable:true}))");
    await wait("!!document.querySelector('[role=tab][data-state=active]')");
    await js("[...document.querySelectorAll('[role=tab]')].find(t=>t.textContent==='Repositories').dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}))");
    await js("[...document.querySelectorAll('button')].find(t=>t.textContent==='Add repository').click()");
    await wait("!!document.querySelector('#watched-repos')");
    await fill('#watched-repos', 'org/new');
    await js("document.querySelector('#watched-repos').dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}))");
    await wait("!!document.querySelector('.repository-editor')");
    assert.equal(await js("window.electronAPI.loadPreferences().then(p=>p.watchedRepos.includes('org/new'))"), false);
    await click('[aria-label="Use global default for inactivity"]');
    await fill('.repository-editor [aria-label="PR inactivity limit in days"]', '90');
    await js("document.querySelector('.repository-editor [aria-label=\"PR inactivity limit in days\"]').focus();document.querySelector('.repository-editor [aria-label=\"PR inactivity limit in days\"]').blur()");
    await click('[aria-label="Use global default for Dependabot"]');
    await click('[aria-label="Repository ignore Dependabot"]');
    await click('[aria-label="Use global default for daily briefing count"]');
    await fill('[aria-label="Repository daily automatic briefings"]', '3');
    await js("document.querySelector('.repository-icon-controls').scrollIntoView({block:'center'})");
    await click('[aria-label="Repository icon"]');
    await wait("!!document.querySelector('[aria-label=\"Search repository icons\"]')");
    assert.ok(await js("document.querySelectorAll('[data-slot=combobox-item]').length<=50"), 'Opening the picker renders a bounded set of icons');
    await fill('[aria-label="Search repository icons"]', 'telescope');
    await wait("!!document.querySelector('[data-value=\"lucide:telescope\"] svg.lucide-telescope')");
    await capture('all-icons');
    win.webContents.sendInputEvent({type:'keyDown', keyCode:'Enter'});
    win.webContents.sendInputEvent({type:'keyUp', keyCode:'Enter'});
    await wait("document.querySelector('[aria-label=\"Repository icon\"]').value==='lucide:telescope'");
    await click('[aria-label="purple repository color"]');
    await js("document.querySelector('.repository-editor').scrollIntoView({block:'start'})");
    assert.equal(await js("document.querySelector('.repository-editor').textContent.includes('3 of 3 left here · 7 left overall')"), true);
    await capture('add-light');
    await button('Watch repository');
    await wait("window.electronAPI.loadPreferences().then(p=>p.repositorySettings?.['org/new']?.color==='purple')");
    assert.equal(await js("window.electronAPI.loadPreferences().then(p=>p.repositorySettings['org/new'].prInactivityDays)"), 90);
    assert.equal(await js("window.electronAPI.loadPreferences().then(p=>p.repositorySettings['org/new'].ignoreDependabotPrs)"), false);
    await click('[aria-label="Configure org/new"]');
    await wait("!!document.querySelector('.repository-editor')");
    assert.equal(await js("document.querySelector('[aria-label=\"Repository daily automatic briefings\"]').value"), '3');
    await button('Cancel');
    await click('[aria-label="Select org/new"]');
    await click('[aria-label="Select klang/engine"]');
    await click('.repository-bulk-actions button');
    await click('[aria-label="Use global default for automatic briefings"]');
    await click('[aria-label="Repository automatic briefings"]');
    await button('Apply to selected repositories');
    await wait("window.electronAPI.loadPreferences().then(p=>p.repositorySettings['org/new'].autoBriefings===false&&p.repositorySettings['klang/engine'].autoBriefings===false)");
    assert.equal(await js("window.electronAPI.loadPreferences().then(p=>p.repositorySettings['org/new'].icon)"), 'lucide:telescope');
    await click('[aria-label="Stop watching org/new"]');
    await wait("window.electronAPI.loadPreferences().then(p=>!p.watchedRepos.includes('org/new'))");
    assert.equal(await js("window.electronAPI.loadPreferences().then(p=>p.repositorySettings['org/new'].color)"), 'purple');
    await click('[data-slot=dialog-close]');
    await wait("!document.querySelector('[role=dialog]')");
    // Repository badges expose the same editor without having to watch the repository first.
    await js("(()=>{const b=document.querySelector('[aria-label=\"Copy repository: klang/engine\"]');const r=b.getBoundingClientRect();b.dispatchEvent(new MouseEvent('contextmenu',{bubbles:true,clientX:r.x+3,clientY:r.y+3,button:2}))})()");
    await wait("[...document.querySelectorAll('[role=menuitem]')].some(e=>e.textContent==='Repository settings…')");
    await js("[...document.querySelectorAll('[role=menuitem]')].find(e=>e.textContent==='Repository settings…').click()");
    await wait("!!document.querySelector('.repository-settings-dialog')");
    await click('[aria-label="blue repository color"]');
    await js("window.selectOption('[aria-label=\"Repository icon\"]', 'emoji')");
    await fill('[aria-label="Repository emoji"]', '🚀');
    await button('Save settings');
    await wait("!document.querySelector('.repository-settings-dialog')");
    assert.equal(await js("document.querySelector('[aria-label=\"Copy repository: klang/engine\"]').classList.contains('repository-color-blue')"), true);
    await capture('queue-light');
    await click('[aria-label="Settings"]');
    await js("[...document.querySelectorAll('[role=tab]')].find(t=>t.textContent==='Repositories').dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}))");
    await click('[aria-label="Configure klang/engine"]');
    await js("document.documentElement.classList.add('dark')");
    win.setSize(640, 750);
    await js("document.querySelector('.repository-editor').scrollIntoView({block:'start'})");
    await capture('narrow-dark');
    assert.equal(await js("document.querySelector('.settings-dialog').scrollWidth<=document.querySelector('.settings-dialog').clientWidth"), true);
    await button('Reset repository settings');
    await button('Save settings');
    await wait("window.electronAPI.loadPreferences().then(p=>!p.repositorySettings['klang/engine'])");
    await click('[data-slot=dialog-close]');
    await wait("!document.querySelector('[role=dialog]')");
    await js("(()=>{const input=document.querySelector('input'); input.focus(); input.dispatchEvent(new KeyboardEvent('keydown',{key:',',metaKey:true,bubbles:true,cancelable:true}))})()");
    await wait("!!document.querySelector('.settings-dialog')");
    await js("document.activeElement.dispatchEvent(new KeyboardEvent('keydown',{key:',',metaKey:true,bubbles:true,cancelable:true}))");
    assert.equal(await js("document.querySelectorAll('.settings-dialog').length"), 1);

    await click('[data-slot=dialog-close]');
    await js("(async()=>{const p=await window.electronAPI.loadPreferences();await window.electronAPI.savePreferences({...p,watchedRepos:Array.from({length:60},(_,i)=>'team/repository-'+String(i).padStart(2,'0'))})})()");
    win.setSize(1280,850);
    await click('[aria-label="Settings"]');
    await js("[...document.querySelectorAll('[role=tab]')].find(t=>t.textContent==='Repositories').dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}))");
    await wait("document.querySelectorAll('.settings-repositories > .repository-settings-list .repository-settings-row').length===60");
    await capture('many-repositories-dark');
    await fill('[aria-label="Filter watched repositories"]', 'repository-5');
    await wait("document.querySelectorAll('.settings-repositories > .repository-settings-list .repository-settings-row').length===10");
    await click('[aria-label="Configure team/repository-55"]');
    await wait("!!document.querySelector('.repository-settings-focus')");
    assert.equal(await js("document.querySelectorAll('.settings-repositories > .repository-settings-list .repository-settings-row').length"),0);
    await click('[aria-label="purple repository color"]');
    await js("[...document.querySelectorAll('button')].find(b=>b.textContent.includes('Back to repositories')).click()");
    await wait("document.querySelector('[aria-label=\"Filter watched repositories\"]')?.value==='repository-5'");
    assert.equal(await js("document.activeElement.getAttribute('aria-label')"), 'Configure team/repository-55');
    await click('[aria-label="Configure team/repository-55"]');
    assert.equal(await js("document.querySelector('[aria-label=\"purple repository color\"]').getAttribute('aria-pressed')"), 'true');
    for (const width of [1280,640]) {
      win.setSize(width,800);
      await capture(`focused-editor-${width}`);
      assert.equal(await js("(()=>{const r=document.querySelector('.repository-editor-actions').getBoundingClientRect();return r.top>=0&&r.bottom<=innerHeight&&r.right<=innerWidth})()"),true);
      assert.equal(await js("document.querySelector('.settings-dialog').scrollWidth<=document.querySelector('.settings-dialog').clientWidth"),true);
    }
    await button('Save settings');
    await wait("window.electronAPI.loadPreferences().then(p=>p.repositorySettings['team/repository-55']?.color==='purple')");
    console.log('PASS: staged watch configuration, overrides, persistence, bulk edits, unwatch retention, badge context menu, live appearance, reset, narrow/dark');
    app.exit(0);
  } catch(error) { console.error(error); await capture('failure'); console.error(await js('document.body.innerText')); app.exit(1); }
});

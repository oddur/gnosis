void test('a test snapshot belongs to both categories; either exclusion hides it, override false wins', () => {
  const kinds = pathFileKinds('__snapshots__/x.snap');
  assert.equal(hiddenByFileFilters(kinds, { hideGenerated: true, hideTests: false }), true);
  assert.equal(hiddenByFileFilters(kinds, { hideGenerated: false, hideTests: true }), true);
  assert.equal(
    hiddenByFileFilters(effectiveFileKinds(kinds, { generated: false, test: false }), {
      hideGenerated: true,
      hideTests: true,
    }),
    false
  );
  assert.notEqual(fileOverrideKey('o/r', 'A.ts'), fileOverrideKey('o/r', 'a.ts'));
});

void test('SQLite filter choices and corrections survive restart and GitHub-cache clearing', async () => {
  const { createAppDataStore } = await import('../src/app-data-store');
  const fs = await import('node:fs'),
    os = await import('node:os'),
    path = await import('node:path');
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gnosis-file-filters-'));
  let data = createAppDataStore();
  try {
    await data.open(dir);
    await createFileFilterState(data).update({
      filters: { hideGenerated: true, hideTests: true, hiddenExtensions: ['.TS', ''] },
    });
    await createFileFilterState(data).update({ repo: 'o/r', path: 'tests/a.ts', override: { test: false } });
    await data.close();
    data = createAppDataStore();
    await data.open(dir);
    await data.clearGitHub();
    await data.close();
    data = createAppDataStore();
    await data.open(dir);
    assert.deepEqual(createFileFilterState(data).read(), {
      hideGenerated: true,
      hideTests: true,
      hiddenExtensions: ['.ts', ''],
      overrides: { [fileOverrideKey('o/r', 'tests/a.ts')]: { test: false } },
    });
  } finally {
    await data.close();
    fs.rmSync(dir, { recursive: true, force: true });
  }
});

void test('classification and negative attribute lookups are reused after restart; new revisions get fresh rules', async () => {
  const { createGitHubClientPool } = await import('../lib/github-client');
  const fs = await import('node:fs'),
    os = await import('node:os'),
    path = await import('node:path');
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gnosis-file-kinds-'));
  let calls = 0,
    updates = 0;
  const fetcher = ((_url: unknown, init: RequestInit) => {
    calls++;
    assert.equal(typeof init.body, 'string');
    const query = (JSON.parse(init.body as string) as { query: string }).query;
    const repository = Object.fromEntries(
      [...query.matchAll(/(a\d+): object\(expression:"([^"\\]+)"\)/g)].map((m) => [
        m[1],
        m[2].endsWith(':.gitattributes') ? { text: '*.ts linguist-generated', byteSize: 24 } : null,
      ])
    );
    return Promise.resolve(
      new Response(JSON.stringify({ data: { repository } }), {
        status: 200,
        headers: { 'content-type': 'application/json' },
      })
    );
  }) as typeof fetch;
  let pool = createGitHubClientPool({ minSpacingMs: 0, fetch: fetcher });
  const done = async (n: number) => {
    for (let i = 0; i < 200 && updates < n; i++) await new Promise((r) => setTimeout(r, 5));
    assert.equal(updates, n);
  };
  try {
    await pool.setStorage(path.join(dir, 'budget.json'));
    let service = createFileClassificationService(() => {
      updates++;
    });
    await service.read(pool.client('fixture'), snapshot);
    await done(1);
    assert.equal(calls, 2);
    await pool.closeStorage();
    pool = createGitHubClientPool({ minSpacingMs: 0, fetch: fetcher });
    await pool.setStorage(path.join(dir, 'budget.json'));
    service = createFileClassificationService(() => {
      updates++;
    });
    assert.equal((await service.read(pool.client('fixture'), snapshot))['src/a.ts'].generated.value, true);
    assert.equal(calls, 2);
    // Another comparison at the same revision reuses both present and absent attribute files.
    await service.read(pool.client('fixture'), { ...snapshot, url: 'https://github.com/o/r/pull/2' });
    await done(2);
    assert.equal(calls, 2);
    await service.read(pool.client('fixture'), {
      ...snapshot,
      metadata: { ...snapshot.metadata, headSha: 'new-head' },
    });
    await done(3);
    assert.equal(calls, 3);
  } finally {
    await pool.closeStorage();
    fs.rmSync(dir, { recursive: true, force: true });
  }
});


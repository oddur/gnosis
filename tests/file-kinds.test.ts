void test('attributes honor root/nested precedence, explicit false, unset, macros and path patterns', () => {
  const files = [
    {
      path: '.gitattributes',
      text: '[attr]gen linguist-generated\n*.ts gen\nsub/** -linguist-generated\n"space name.ts" linguist-generated=false\n**/api?.[ch] linguist-generated\n!bad linguist-generated\nfolder/ linguist-generated',
    },
    { path: 'sub/.gitattributes', text: 'deep/*.ts linguist-generated\nplain.ts !linguist-generated' },
  ];
  assert.equal(generatedAttribute('x/a.ts', files)?.value, true);
  assert.equal(generatedAttribute('sub/a.ts', files)?.value, false);
  assert.equal(generatedAttribute('sub/deep/a.ts', files)?.value, true);
  assert.equal(generatedAttribute('sub/plain.ts', files), undefined);
  assert.equal(generatedAttribute('space name.ts', files)?.value, false);
  assert.equal(generatedAttribute('api1.c', files)?.value, true);
  assert.equal(generatedAttribute('folder/x.txt', files), undefined);
});
void test('preferences and per-repository overrides persist independently of viewed state', async () => {
  const values = new Map<string, unknown>();
  let flushes = 0;
  const storage = {
    read: (key: string) => structuredClone(values.get(key)),
    write: (key: string, value: unknown) => {
      values.set(key, structuredClone(value));
    },
    flush: () => {
      flushes++;
      return Promise.resolve();
    },
  };
  const store = createFileFilterState(storage);
  assert.equal(store.read().hideGenerated, false);
  await store.update({ filters: { hideGenerated: true, hideTests: false } });
  await store.update({ repo: 'o/r', path: 'tests/foo.ts', override: { test: false } });
  const restored = createFileFilterState(storage).read();
  assert.equal(restored.hideGenerated, true);
  assert.deepEqual(restored.overrides[fileOverrideKey('o/r', 'tests/foo.ts')], { test: false });
  assert.equal(restored.overrides[fileOverrideKey('other/r', 'tests/foo.ts')], undefined);
  await store.update({ repo: 'o/r', path: 'tests/foo.ts', override: {} });
  assert.deepEqual(store.read().overrides, {});
  assert.equal(flushes, 3);
});
void test('classification returns paths immediately, batches attributes in background and explicit false beats cached headers', async () => {
  const calls: { query: string; repo: string }[] = [];
  let release: () => void = () => {};
  const gate = new Promise<void>((resolve) => {
    release = resolve;
  });
  const client = {
    graphql: async (query: string, args: { name: string }) => {
      calls.push({ query, repo: args.name });
      await gate;
      const objects: Record<string, { text: string; byteSize: number } | null> = {};
      for (const match of query.matchAll(/(a\d+): object\(expression:"([^"\\]+)"\)/g))
        objects[match[1]] = match[2].endsWith(':.gitattributes')
          ? { text: '*.ts linguist-generated=false', byteSize: 30 }
          : null;
      return { repository: objects };
    },
  } as unknown as Octokit;
  let updates = 0;
  const service = createFileClassificationService(() => {
    updates++;
  });
  const first = await service.read(client, snapshot);
  assert.equal(first['src/a.ts'].generated.value, false);
  await service.observe(client, snapshot, snapshot.files[0], {
    before: { kind: 'absent' },
    after: { kind: 'text', content: '// @generated\nconst x=1;' },
  });
  assert.equal((await service.read(client, snapshot))['src/a.ts'].generated.value, true);
  release();
  for (let i = 0; i < 30 && updates < 2; i++) await new Promise((r) => setTimeout(r, 5));
  const later = await service.read(client, snapshot);
  assert.equal(later['src/a.ts'].generated.value, false);
  assert.match(later['src/a.ts'].generated.reason, /gitattributes/);
  assert.equal(calls.length, 2, 'head and base repositories are queried separately');
  assert.match(calls[0].query, /head:src\/\.gitattributes/);
  assert.match(calls[1].query, /base:\.gitattributes/);
});


/** A conservative raw-diff classifier. Deliberately separate from AI input filtering. */
export function pathFileKinds(path: string): FileKinds {
  const parts = path.split('/'),
    name = parts.at(-1) ?? '',
    lower = name.toLowerCase();
  let generated = 'No generated-file signal';
  if (generatedNames.has(lower)) generated = `Known lockfile: ${name}`;
  else if (
    /\.(?:min\.(?:js|css)|(?:js|css)\.map|generated\.[^.]+|g\.dart|freezed\.dart|pb\.go|pb\.h|pb\.cc|pb\.c|pbf\.go)$/i.test(
      name
    ) ||
    /_pb2(?:_grpc)?\.py$/.test(name)
  )
    generated = 'Generated filename convention';
  else if (lower.endsWith('.snap')) generated = 'Generated test snapshot';
  else if (parts.slice(0, -1).some((p) => ['__generated__', 'generated'].includes(p.toLowerCase())))
    generated = 'Inside a generated-code directory';
  let test = 'No test-file signal';
  const directory = parts.slice(0, -1).find((p) => /^(?:tests?|__tests__|__snapshots__|testdata|e2e|specs?)$/i.test(p));
  const config =
    /^(?:(?:jest|vitest|playwright|cypress|karma|pytest|tox|conftest)\.config\.[^.]+|conftest\.py|pytest\.ini|tox\.ini)$/.test(
      lower
    ) || /\.config\.[^.]+$/.test(lower);
  const exampleOrBenchmark = parts.slice(0, -1).some((p) => /^(?:examples?|benchmarks?|benches)$/i.test(p));
  if (directory && !config && !exampleOrBenchmark) test = `Inside ${directory}/`;
  else if (
    !config &&
    !exampleOrBenchmark &&
    (/\.(?:test|spec)\.[^.]+$/i.test(name) ||
      /^test_.+\.py$/i.test(name) ||
      /(?:_test\.(?:go|rs|py|rb)|_spec\.rb|(?:Test|Tests|Spec)\.(?:java|kt|scala|cs|swift))$/.test(name))
  )
    test = 'Test filename convention';
  return {
    generated: { value: generated !== 'No generated-file signal', reason: generated },
    test: { value: test !== 'No test-file signal', reason: test },
  };
}
export function generatedHeader(text: string): boolean {
  // Look only at the header, never arbitrary strings in the file body or diff removals.
  return text
    .slice(0, 8192)
    .split('\n')
    .slice(0, 40)
    .some(
      (line) =>
        /^\s*(?:\/\/|\/\*|\*|#|<!--|--|;|%)/.test(line) &&
        /(?:code generated[^\n]*do not edit|@generated\b|<auto-generated\b|automatically generated[^\n]*(?:do not (?:edit|modify)|file)|generated (?:by|from)[^\n]*do not (?:edit|modify)|this file (?:is|was) (?:auto-?generated|generated by))/i.test(
          line
        )
    );
}
export function effectiveFileKinds(kinds: FileKinds, override?: FileKindOverride): FileKinds {
  return {
    generated:
      override?.generated === undefined
        ? kinds.generated
        : { value: override.generated, reason: 'Your override for this repository and path' },
    test:
      override?.test === undefined
        ? kinds.test
        : { value: override.test, reason: 'Your override for this repository and path' },
  };
}
export const hiddenByFileFilters = (kinds: FileKinds, filters: Pick<FileFilterState, 'hideGenerated' | 'hideTests'>) =>
  (filters.hideGenerated && kinds.generated.value) || (filters.hideTests && kinds.test.value);

/** Last filename suffix, case-insensitive; dotfiles without a suffix have no extension. */
export function fileExtension(path: string): string {
  const name = path.split('/').at(-1) ?? '';
  const dot = name.lastIndexOf('.');
  return dot > 0 && dot < name.length - 1 ? name.slice(dot).toLowerCase() : '';
}

export const hiddenByFileExtensions = (path: string, extensions: string[]) => extensions.includes(fileExtension(path));

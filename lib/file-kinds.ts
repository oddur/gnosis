import type { PrChangeFile, PrChanges } from './pr-changes';
export interface FileKindEvidence {
  value: boolean;
  reason: string;
}
export interface FileKinds {
  generated: FileKindEvidence;
  test: FileKindEvidence;
}
export interface FileKindOverride {
  generated?: boolean;
  test?: boolean;
}
export interface FileFilterState {
  hideGenerated: boolean;
  hideTests: boolean;
  hiddenExtensions: string[];
  overrides: Record<string, FileKindOverride>;
}
export const DEFAULT_FILE_FILTERS: FileFilterState = {
  hideGenerated: false,
  hideTests: false,
  hiddenExtensions: [],
  overrides: {},
};
export const fileOverrideKey = (repo: string, path: string) => JSON.stringify([repo.toLowerCase(), path]);
export const classificationKey = (s: PrChanges) =>
  JSON.stringify([s.url, s.comparisonBase, s.metadata.headSha, !!s.comparison, ...(s.stackComparison ? [s.stackComparison.key] : [])]);
export function fileSource(s: PrChanges, f: PrChangeFile) {
  const deleted = f.status === 'deleted';
  const fallback = new URL(s.url).pathname.split('/').slice(1, 3).join('/');
  return {
    repo: (deleted ? s.metadata.baseRepo : s.metadata.headRepo) ?? fallback,
    ref: deleted ? s.comparisonBase : s.metadata.headSha,
    path: f.path,
  };
}

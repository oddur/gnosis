"""Build WOFF2 subsets without losing glyphs or the variable weight axis.

Requires: fonttools[woff]==4.68.0 (development only; generated files are committed).
Run from any directory with: python3 site/scripts/build-fonts.py
"""
from pathlib import Path
from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
source = root / "fonts/onest-variable.ttf"
original = TTFont(source)
points = set(original.getBestCmap())
# Latin plus punctuation, currency, arrows, and mathematical symbols used by the UI.
latin = set(range(0x100)) | set(range(0x2000, 0x2070))
latin |= {0x131, 0x152, 0x153, 0x2BB, 0x2BC, 0x2C6, 0x2DA, 0x2DC,
          0x304, 0x308, 0x329, 0x2074, 0x20AC, 0x2122, 0xFEFF, 0xFFFD}
latin |= set(range(0x2190, 0x2300)) | {0x2713, 0x27F5, 0x27F6}
faces = []
covered = set()
for name, chars in [("latin", points & latin), ("extended", points - latin)]:
    font = TTFont(source)
    options = subset.Options()
    options.layout_features = ["*"]
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=chars)
    subsetter.subset(font)
    font.flavor = "woff2"
    target = root / f"public/fonts/onest-{name}.woff2"
    font.save(target)
    result = TTFont(target)
    assert set(result.getBestCmap()) == chars
    assert [(a.axisTag, a.minValue, a.maxValue) for a in result["fvar"].axes] == [
        (a.axisTag, a.minValue, a.maxValue) for a in original["fvar"].axes
    ]
    for cp, glyph in result.getBestCmap().items():
        assert result["hmtx"].metrics[glyph] == original["hmtx"].metrics[original.getBestCmap()[cp]]
    covered |= chars
    ranges = []
    for cp in sorted(chars):
        if ranges and cp == ranges[-1][1] + 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    unicode_range = ", ".join(f"U+{a:04X}" + (f"-{b:04X}" if a != b else "") for a, b in ranges)
    faces.append(f"""@font-face {{
  font-family: Onest;
  src: url('/fonts/onest-{name}.woff2') format('woff2');
  font-weight: 100 900;
  font-display: swap;
  unicode-range: {unicode_range};
}}""")
    print(f"{target.name}: {target.stat().st_size:,} bytes, {len(chars)} characters")
assert covered == points
(root / "src/styles/fonts.css").write_text(
    "/* Generated by scripts/build-fonts.py. Source and license: fonts/README.md. */\n" + "\n".join(faces) + "\n"
)
